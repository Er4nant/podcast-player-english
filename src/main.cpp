// Hardware: M5Stack Cardputer ADV (ESP32-S3, 8MB Flash, no PSRAM)
// Display: ST7789, native 135x240 + rotation 1 -> canvas 240x135 (M5GFX 0.2.33)
// Audio: onboard ES8311 codec, I2C bus SDA=8 / SCL=9 (auto-initialized by M5Unified),
//        I2S_NUM_1, BCLK=41 / WS=43 / DOUT=42, no MCLK line
//        (ES8311 register 0x01=0xB5 sets MCLK=BCLK).
//        Speaker and 3.5mm headphone share the HP driver output path (register 0x13=0x10).
//
// Audio backend: ESP32-audioI2S 3.0.12 (HTTPS insecure / redirects / built-in M4A-AAC).
// Wi-Fi setup: tzapu/WiFiManager v2.0.17 -- device starts hotspot PodcastPlayer; phone joins
// and the config page pops up (192.168.4.1) to pick a network and enter the password;
// credentials are stored in NVS, no hardcoded WiFi. Feed source (Xiaoyuzhou) is all .m4a; ESP8266Audio cannot handle the MP4 container (v1 lesson).
//
// UI (v3.4 black-and-white palette: pure black background + white text with gray levels; only cover art is color):
//   - List page: status bar + 6-row episode list, Enter plays and opens the player page
//   - Player page: 100x100 embedded cover on the left (cover.h, generated by gen_cover.py),
//     right side channel name / two-line title / white progress bar / current and total time; progress redraws locally each second
//   - Keys: ';'/w and '.'/s move the cursor (list page) or return to the list (player page)
//     Enter play/pause/resume, '+'/'=' and '-'/'_' volume, '`' exits to M5Launcher
//   - On end of file (EOF) it auto-sets "Finished" and refreshes the screen
//
// Known limits (MVP trade-offs): pause uses pauseResume(); position is exact while the connection is alive;
// if paused too long the CDN may disconnect, then press Enter to restart from the beginning.
//
// Key implementation notes:
//   - ES8311 is initialized after connecttohost succeeds (I2S clock already running),
//     mirroring the timing of M5Unified's speaker post-start callback.
//   - An app launched by M5Launcher stays in this app after reboot (otadata),
//     so a key to return to the Launcher must be provided.
// =====================================================================

