static int         showTop    = 0;
static std::string searchQuery;
static uint32_t    searchOpenedMs = 0;      // ignore typing for a moment after opening (the 'f' keypress itself)

// Percent-encode a search term for a URL query string.
static std::string urlEncodeQuery(const std::string& s) {
  std::string out;
  char buf[4];
  for (unsigned char c : s) {
    if (isalnum(c) || c == '-' || c == '_' || c == '.' || c == '~') {
      out += (char)c;
    } else if (c == ' ') {
      out += '+';
    } else {
      snprintf(buf, sizeof(buf), "%%%02X", (unsigned)c);
      out += buf;
    }
  }
  return out;
}

// GET a JSON endpoint and hand the body stream to `parse`. HTTPS is certificate-checked
// against the built-in CA bundle. Returns parse's result (false on any failure).
template <typename Parse>
static bool httpGetJson(const String& url, Parse parse) {
  WiFiClientSecure secure;
  secure.setCACertBundle(_binary_x509_crt_bundle_start);
  HTTPClient http;
  if (!http.begin(secure, url)) return false;
  http.setFollowRedirects(HTTPC_STRICT_FOLLOW_REDIRECTS);
  http.setUserAgent("CardputerPodcast/1.0");
  http.setConnectTimeout(10000);
  http.setTimeout(10000);
  int code = http.GET();
  bool ok = false;
  if (code == HTTP_CODE_OK) {
    WiFiClient* stream = http.getStreamPtr();
    if (stream != nullptr) {
      stream->setTimeout(8000);
      ok = parse(*stream);
    }
  } else {
    Serial.printf("[catalog] HTTP %d\n", code);
  }
  http.end();
  return ok;
}

// Look up the RSS feed URL for an Apple show id (charts only return names and ids).
static std::string lookupFeedUrl(uint64_t id) {
  char url[160];
  snprintf(url, sizeof(url),
           "https://itunes.apple.com/lookup?id=%llu&entity=podcast",
           (unsigned long long)id);
  std::string feed;
  httpGetJson(String(url), [&feed](Stream& s) {
    feed = parseLookupFeedUrl(s);
    return !feed.empty();
  });
  return feed;
}

// Fill `shows` from a charts or search URL. Returns true if anything was parsed.
static bool loadShowList(const String& url, bool search) {
  shows.clear();
  showCursor = 0;
  showTop    = 0;
  if (search) {
    return httpGetJson(url, [](Stream& s) {
      return parseSearchJson(s, shows, SEARCH_LIMIT) > 0;
    });
  }
  return httpGetJson(url, [](Stream& s) {
    return parseChartsJson(s, shows, CHARTS_LIMIT) > 0;
  });
}

