// Open the config hotspot (blocking): WiFiManager runs a webserver + DNS internally until connected
// or timeout. On first boot with no credentials, setup goes through autoConnect (tries stored credentials first);
// afterwards press 0 to reconfigure here. Returns whether WiFi connected.
static bool openPortal() {
  WiFiManager wm;
  makePortalPassword();
  wm.setConnectTimeout(10);        // wait for a connect attempt with stored credentials
  wm.setConfigPortalTimeout(180);  // auto-close the hotspot after 3 min of inactivity
  wm.setAPCallback([](WiFiManager*) { drawPortalScreen(); });
#ifdef PODCAST_TARGET_STICKS3
  // Config page includes channel settings: prefills the currently active channel; saving switches channels (stored
  // in NVS, no reflash). Saving with the RSS field cleared = restore the firmware built-in channel
  WiFiManagerParameter prmName("chan", "Channel name", channels[0].name.c_str(), 48);
  WiFiManagerParameter prmRss("rss", "Podcast RSS URL",
                              channels[0].rss.c_str(), 256);
  wm.addParameter(&prmName);
  wm.addParameter(&prmRss);
#endif
  bool ok = wm.startConfigPortal(AP_NAME, portalPass);
  wifiOk = ok && (WiFi.status() == WL_CONNECTED);
  if (wifiOk) {
    WiFi.setSleep(false);           // online streaming needs stable throughput
    WiFi.setAutoReconnect(true);    // auto-reconnect at the low level after a router blip
  }
#ifdef PODCAST_TARGET_STICKS3
  if (applyPortalChannel(prmName.getValue(), prmRss.getValue())) {
    refetchNeeded = true;  // top of loop triggers refetch of the new channel
  }
#endif
  uiDirty = true;                    // restore main UI (redrawn in loop)
  return wifiOk;
}

