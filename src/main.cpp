// Enter on the search page: run the query.
static void runSearch() {
  if (searchQuery.empty()) return;
  statusMsg = "Searching...";
  uiDirty = true;
  drawUI();
  String url = String("https://itunes.apple.com/search?media=podcast&entity=podcast&country=") +
               CATALOG_COUNTRY + "&limit=" + String(SEARCH_LIMIT) +
               "&term=" + urlEncodeQuery(searchQuery).c_str();
  showsAreSearch = true;
  bool ok = loadShowList(url, true);
  view = VIEW_SHOWS;
  statusMsg = ok ? "" : "No results (or search failed)";
  uiDirty = true;
}

// Enter on a show: resolve its feed, stop playback and load its episodes.
static void openShow(int idx) {
  if (idx < 0 || idx >= (int)shows.size()) return;
  ShowEntry show = shows[idx];  // copy: the list may be rebuilt below
  statusMsg = "Loading: " + show.name;
  uiDirty = true;
  drawUI();
  std::string feed = show.feedUrl.empty() ? lookupFeedUrl(show.id) : show.feedUrl;
  if (feed.empty()) {
    statusMsg = "No feed for this show";
    uiDirty = true;
    return;
  }
  if (audio.isRunning()) {
    audio.stopSong();
    while (audio.isRunning()) delay(10);
  }
  paused         = false;
  player.current = -1;
  activeFeedUrl  = feed;
  activeFeedName = show.name;
  episodes.clear();
  fetchEpisodesUrl(feed, episodes);
  cursor    = 0;
  scrollTop = 0;
  view      = VIEW_LIST;
  statusMsg = episodes.empty() ? "Fetch failed, Enter: retry" : "";
  uiDirty   = true;
}

// Keyboard input for the search page (Cardputer only). Adds typed characters,
// handles Backspace. Ignores keys held down when the page opened.
#ifndef PODCAST_TARGET_STICKS3
static void handleSearchTyping() {
  if (millis() - searchOpenedMs < 300) return;
  auto& kb = M5Cardputer.Keyboard;
  auto st = kb.keysState();
  static bool hadKeys = false;
  bool hasKeys = !st.word.empty() || st.del;
  if (hasKeys && !hadKeys) {  // new key press only (edge)
    for (char c : st.word) {
      if (searchQuery.size() < SEARCH_MAX_CHARS && c >= 32 && c < 127) searchQuery += c;
    }
    if (st.del && !searchQuery.empty()) searchQuery.pop_back();
    uiDirty = true;
  }
  hadKeys = hasKeys;
}
#endif  // !PODCAST_TARGET_STICKS3

