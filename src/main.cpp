// Clean XML text: strip newlines/tabs, collapse runs of spaces, trim leading/trailing whitespace
static std::string cleanText(const char* raw) {
  std::string out;
  if (raw == nullptr) return out;
  out.reserve(strlen(raw));
  bool prevSpace = true;  // also swallow leading spaces
  for (const char* p = raw; *p; ++p) {
    unsigned char c = (unsigned char)*p;
    if (c == '\r' || c == '\n' || c == '\t') c = ' ';
    if (c == ' ') {
      if (prevSpace) continue;
      prevSpace = true;
    } else {
      prevSpace = false;
    }
    out.push_back((char)c);
  }
  while (!out.empty() && out.back() == ' ') out.pop_back();
  return out;
}

// Byte-sequence length and display width of a single UTF-8 char (efontCN_16: full-width 16px, half-width 8px)
static void utf8CharAt(const std::string& s, size_t i, int& seq, int& cw) {
  unsigned char c = (unsigned char)s[i];
  if      (c >= 0xF0) { seq = 4; cw = 16; }
  else if (c >= 0xE0) { seq = 3; cw = 16; }
  else if (c >= 0xC0) { seq = 2; cw = 8;  }
  else                { seq = 1; cw = 8;  }
}

// Truncate by display width (appends "..."; never cuts inside a multibyte char)
static std::string fitText(const std::string& s, int max_px) {
  const int ellipsis_px = 3 * 8;
  int w = 0;
  size_t i = 0;
  while (i < s.size()) {
    int seq, cw;
    utf8CharAt(s, i, seq, cw);
    if (w + cw > max_px - ellipsis_px) {
      size_t cut = i;
      while (cut > 0 && ((unsigned char)s[cut] & 0xC0) == 0x80) --cut;
      return s.substr(0, cut) + "...";
    }
    w += cw;
    i += seq;
  }
  return s;
}

// Wrap by display width (at most max_lines lines; the last line gets "..." if it overflows)
static std::vector<std::string> wrapText(const std::string& s, int max_px,
                                         int max_lines) {
  std::vector<std::string> lines;
  size_t i = 0;
  while (i < s.size() && (int)lines.size() < max_lines) {
    std::string line;
    int w = 0;
    bool overflow = false;
    while (i < s.size()) {
      int seq, cw;
      utf8CharAt(s, i, seq, cw);
      if (w + cw > max_px) {
        // current line has more content -> mark as wrapped
        if ((int)lines.size() == max_lines - 1) overflow = true;
        break;
      }
      line += s.substr(i, seq);
      w += cw;
      i += seq;
    }
    if (overflow) {
      // last line can't hold the rest: back off one char and append an ellipsis
      while (!line.empty() && ((unsigned char)line.back() & 0xC0) == 0x80) {
        line.pop_back();
      }
      if (!line.empty()) line.pop_back();
      // re-crop by ellipsis width after backing off the char
      int lw = 0;
      for (size_t k = 0; k < line.size();) {
        int seq, cw;
        utf8CharAt(line, k, seq, cw);
        lw += cw;
        k += seq;
      }
      while (lw > max_px - 24 && !line.empty()) {
        char lc = line.back();
        line.pop_back();
        lw -= ((lc & 0x80) == 0) ? 8 : 0;
        // trailing bytes of a multibyte char are peeled one by one; fix width until the char head is reached
        if (!line.empty() && ((unsigned char)line.back() & 0xC0) == 0x80) {
          continue;
        }
        break;
      }
      line += "...";
    }
    lines.push_back(line);
  }
  return lines;
}

// seconds -> "mm:ss" or "h:mm:ss"
static std::string fmtTime(uint32_t sec) {
  if (sec == 0) return "--:--";
  char buf[16];
  uint32_t h = sec / 3600, m = (sec % 3600) / 60, s = sec % 60;
  if (h > 0) {
    snprintf(buf, sizeof(buf), "%u:%02u:%02u",
             (unsigned)h, (unsigned)m, (unsigned)s);
  } else {
    snprintf(buf, sizeof(buf), "%02u:%02u", (unsigned)m, (unsigned)s);
  }
  return buf;
}

