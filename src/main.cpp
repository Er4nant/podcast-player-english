// Uses Apple's public JSON endpoints (no API key). Results go to VIEW_SHOWS; opening
// a show loads its RSS into the normal episode list via activeFeedUrl.
static const char* const CATALOG_COUNTRY = "au";  // storefront for charts and search
static constexpr int CHARTS_LIMIT = 25;
static constexpr int SEARCH_LIMIT = 20;
static constexpr size_t SEARCH_MAX_CHARS = 40;

