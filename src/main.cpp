// 'o' key: flip episode order (feeds are normally newest-first). Keeps the selected
// and playing episodes selected after the reversal.
static bool episodesOldestFirst = false;
static void syncScroll();
static void toggleEpisodeOrder() {
  if (episodes.size() < 2) return;
  std::string selUrl = (player.current >= 0 && player.current < (int)episodes.size())
                           ? episodes[player.current].url
                           : (cursor < (int)episodes.size() ? episodes[cursor].url : std::string());
  std::reverse(episodes.begin(), episodes.end());
  episodesOldestFirst = !episodesOldestFirst;
  for (int i = 0; i < (int)episodes.size(); ++i) {
    if (episodes[i].url == selUrl) {
      if (player.current >= 0) player.current = i;
      cursor = i;
      break;
    }
  }
  syncScroll();
  statusMsg = episodesOldestFirst ? "Oldest first" : "Newest first";
  uiDirty = true;
}

static void syncScroll() {
  if (cursor < scrollTop) scrollTop = cursor;
  if (cursor >= scrollTop + listLines) scrollTop = cursor - listLines + 1;
}

