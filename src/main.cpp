// Write ES8311 registers via M5Unified's internal I2C bus (CardputerADV: SDA=8 / SCL=9,
// M5.begin already auto-initializes it)
static bool es8311Write(uint8_t addr, uint8_t reg, uint8_t val) {
  return M5.In_I2C.writeRegister8(addr, reg, val, 100000);
}

// ES8311 init. The register sequence is copied verbatim from M5Unified 0.2.26's
// CardputerADV speaker callback (src/M5Unified.inl).
// Must be called after the I2S clock is running (M5Unified does this write in the
// speaker post-start callback), so it runs after connecttohost succeeds.
static bool initEs8311() {
  uint8_t addr = ES8311_ADDR;
  if (!es8311Write(addr, 0x00, 0x80)) {       // write RESET first to probe the address
    addr = 0x19;
    if (!es8311Write(addr, 0x00, 0x80)) {
      Serial.println("[audio] ES8311 not found (0x18/0x19)");
      return false;
    }
  }
  static const uint8_t seq[][2] = {
      {0x00, 0x80},  // 0x00 RESET   / CSM POWER ON
      {0x01, 0xB5},  // 0x01 CLOCK_MANAGER / MCLK=BCLK (no separate MCLK line needed)
      {0x02, 0x18},  // 0x02 CLOCK_MANAGER / MULT_PRE=3
      {0x0D, 0x01},  // 0x0D SYSTEM   / power up the analog circuit
      {0x12, 0x00},  // 0x12 SYSTEM   / enable the DAC
      {0x13, 0x10},  // 0x13 SYSTEM   / enable the HP driver output (shared by speaker + headphone)
      {0x32, 0xBF},  // 0x32 DAC      / hardware volume +-0dB; setVolume is applied in software
      {0x37, 0x08},  // 0x37 DAC      / bypass the DAC equalizer
  };
  bool ok = true;
  for (auto& r : seq) ok = es8311Write(addr, r[0], r[1]) && ok;
#ifdef PODCAST_TARGET_STICKS3
  // StickS3's amp enable is NOT done here: the bitOn current surge, if it overlaps
  // connecttohost's TLS handshake, triggers brownout; instead it is enabled with a delay
  // by ampTick() after startPlayback succeeds (see ampEnableAt)
#endif
  Serial.printf("[audio] ES8311 init @0x%02X %s\n", addr, ok ? "ok" : "FAIL");
  return ok;
}

// Amp switch (only StickS3 has a separate PA enable bit; the Cardputer amp is driven along with the codec output)
static void setAmp(bool on) {
#ifdef PODCAST_TARGET_STICKS3
  if (on) M5.In_I2C.bitOn(M5PM1_ADDR, 0x11, 0b00001000, 100000);
  else    M5.In_I2C.bitOff(M5PM1_ADDR, 0x11, 0b00001000, 100000);
#else
  (void)on;
#endif
}

// Called every loop pass: enable the amp when due and fade the volume in step (non-blocking).
// After enabling, drop to a low volume first, then step up to the user volume every 150ms, avoiding pop and a second current surge
static void ampTick() {
  if (ampEnableAt != 0 && (int32_t)(millis() - ampEnableAt) >= 0) {
    ampEnableAt = 0;
    setAmp(true);
    ampFadeNow = 3;
    audio.setVolume(ampFadeNow);
    ampFadeAt = millis() + 150;
    Serial.println("[audio] amp on (delayed)");
  }
  if (ampFadeNow != 0 && (int32_t)(millis() - ampFadeAt) >= 0) {
    int target = player.volume;
    ampFadeNow += 3;
    if (ampFadeNow >= target) {
      audio.setVolume(target);
      ampFadeNow = 0;
    } else {
      audio.setVolume(ampFadeNow);
      ampFadeAt = millis() + 150;
    }
  }
}

// --------------------------- Playback control ---------------------------

static void startPlayback(int idx) {
  if (audio.isRunning()) audio.stopSong();
  paused = false;
  wifiDropPause = false;  // user started playback; clear the drop-wait flag
  player.current = idx;
  // Keep the amp off during connection: enable is delayed to 600ms after connect succeeds (ampTick),
  // staggered from the DNS+TLS+first-block download WiFi current spike, avoiding a brownout reboot
  setAmp(false);
  ampFadeNow = 0;

  // connecttohost blocks synchronously for seconds (DNS+TLS+GET+m4a header parse); draw the hint first
  statusMsg = "Buffering...";
  uiDirty = true;
  drawUI();
  uiDirty = false;

  if (!i2sConfigured) {
    // no MCLK pin (ES8311 already configured MCLK=BCLK)
#ifdef PODCAST_TARGET_STICKS3
    audio.setPinout(PIN_I2S_BCLK, PIN_I2S_WS, PIN_I2S_DOUT, PIN_I2S_MCLK);
#else
    audio.setPinout(PIN_I2S_BCLK, PIN_I2S_WS, PIN_I2S_DOUT);
#endif
    // Note: audioI2S 3.0.12 already calls InBuff.init() in the constructor (fixed 16000B),
    // setBufsize() is rejected by isInitialized(), so the buffer size can't be changed
    audio.setVolumeSteps(VOLUME_MAX);
    audio.setVolume(player.volume);
    audio.setConnectionTimeout(8000, 15000);
    i2sConfigured = true;
  }

  // Connect directly to the original https address. Do NOT change to plain http: this feed's audio goes
  // through the dts-api.xiaoyuzhoufm.com relay, which returns 302 for http requests with an all-uppercase
  // "HTTPS://..." Location; audioI2S 3.0.12 can't parse that redirect, showing
  // "connected" but no audio in the stream (duration stays --:--:--).
  // https requests redirect to a lowercase https://media.xyzcdn.net/... direct link, which works fine.
  uint32_t t0 = millis();
  Serial.printf("[audio] startPlayback idx=%d heap=%u\n", idx,
                (unsigned)ESP.getFreeHeap());
  bool ok = audio.connecttohost(episodes[idx].url.c_str());
  Serial.printf("[audio] connecttohost returned ok=%d after %ums\n",
                (int)ok, (unsigned)(millis() - t0));
  if (ok && !es8311Ready) {
    // I2S clock is already running; initializing ES8311 now matches M5Unified's timing
    es8311Ready = initEs8311();
    if (!es8311Ready) Serial.println("[audio] ES8311 init failed, no sound");
  }
  if (ok && es8311Ready) {
    // 600ms later loop->ampTick turns the amp on and fades in: the TLS burst is over by then,
    // and the input ring (12KB, ~1s of audio) covers this gap with no feed flow
    ampEnableAt = millis() + 600;
  }
  statusMsg = ok ? "" : "Connect failed";
  view = VIEW_PLAYER;   // enter the player page
  uiDirty = true;
}

