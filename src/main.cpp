// Exit to M5Launcher: an app launched by the Launcher stays in this app after reboot (otadata),
// so the boot partition must be explicitly switched back to the Launcher before rebooting
static void returnToLauncher() {
  const esp_partition_t* part = esp_ota_get_next_update_partition(nullptr);
  if (part != nullptr) {
    esp_ota_set_boot_partition(part);
  }
  esp_restart();
}

static void handleKeys() {
#ifdef PODCAST_TARGET_STICKS3
  // ---- StickS3 two-button input layer: translates BtnA/BtnB events into the same input primitives as the keyboard ----
  // list page: A click=down  A long-hold repeat=up  B click=play selected  B hold 1.5s=WiFi setup
  // player page: A click=back to list  A long-hold repeat=volume+  B click=play/pause  B long-hold repeat=volume-
  bool up = false, down = false, volUp = false, volDn = false;
  bool back = false, cfg = false;
  bool enter = M5.BtnB.wasClicked();  // B click = Enter (edge-triggered)
  {
    static uint32_t aPressMs = 0, bPressMs = 0, aLast = 0, bLast = 0;
    static bool     bCfgDone = false;
    static uint32_t downUntil = 0, upUntil = 0, cfgUntil = 0;
    const uint32_t  now = millis();
    const bool      aOn = M5.BtnA.isPressed();
    const bool      bOn = M5.BtnB.isPressed();
    if (aOn && aPressMs == 0) { aPressMs = now; aLast = 0; }
    if (bOn && bPressMs == 0) { bPressMs = now; bLast = 0; bCfgDone = false; }
    if (!aOn) aPressMs = 0;
    if (!bOn) bPressMs = 0;
    const bool inPlayer = (view == VIEW_PLAYER);
    if (M5.BtnA.wasClicked()) {              // A click
      if (inPlayer) upUntil = now + 120;     //   player page -> back to list
      else          downUntil = now + 120;   //   list page -> move down
    }
    if (aOn && now - aPressMs >= 500) {      // A long press (M5Unified hold threshold is also 500ms)
      if (inPlayer) {                        //   player page: volume+ repeat
        if (now - aLast >= 250) { volUp = true; aLast = now; }
      } else if (now - aLast >= 350) {       //   list page: move up repeat
        upUntil = now + 120; aLast = now;
      }
    }
    if (bOn && now - bPressMs >= 500 && inPlayer) {  // B long press: volume- repeat
      if (now - bLast >= 250) { volDn = true; bLast = now; }
    }
    if (bOn && now - bPressMs >= 1500 && !inPlayer && !bCfgDone) {
      cfgUntil = now + 120;  // list page B hold 1.5s: open WiFi setup
      bCfgDone = true;       // don't re-trigger after returning from setup until released
    }
    down = now < downUntil;
    up   = now < upUntil;
    cfg  = now < cfgUntil;
  }
#else
  auto& kb = M5Cardputer.Keyboard;
  bool up    = kb.isKeyPressed(';') || kb.isKeyPressed('w');
  bool down  = kb.isKeyPressed('.') || kb.isKeyPressed('s');
  bool volUp = kb.isKeyPressed('=') || kb.isKeyPressed('+');
  bool volDn = kb.isKeyPressed('-') || kb.isKeyPressed('_');
  bool back  = kb.isKeyPressed('`');
  bool enter = kb.keysState().enter;
  bool cfg   = false;  // '0' key is read in the setup block below
#endif
#ifndef PODCAST_TARGET_STICKS3
  if (view == VIEW_SEARCH) {       // while typing, letters must not move the cursor or change volume
    up = down = volUp = volDn = false;
    handleSearchTyping();
  }
#endif

  if (back) {
    returnToLauncher();  // does not return
  }

  // ---- up/down: move cursor on the list page; return to the list on the player page ----
  static bool     lastUp = false, lastDown = false;
  static uint32_t lastNavMs = 0;
  uint32_t now = millis();
  if (up != lastUp || down != lastDown) lastNavMs = 0;
  lastUp = up;
  lastDown = down;
  if (up || down) {
    if (view == VIEW_PLAYER) {
      if (now - lastNavMs >= 200) {
        view = VIEW_LIST;   // player page up/down key -> back to list
        lastNavMs = now;
        uiDirty = true;
      }
    } else if (view == VIEW_CHANNEL && now - lastNavMs >= 160) {
      // channel page: cursor moves over the channel list
      if (up && chanCursor > 0) {
        --chanCursor;
        lastNavMs = now;
        uiDirty = true;
      }
      if (down && chanCursor < (int)channels.size() - 1) {
        ++chanCursor;
        lastNavMs = now;
        uiDirty = true;
      }
    } else if (view == VIEW_SHOWS && now - lastNavMs >= 160) {
      if (up && showCursor > 0) {
        --showCursor;
        lastNavMs = now;
        uiDirty = true;
      }
      if (down && showCursor < (int)shows.size() - 1) {
        ++showCursor;
        lastNavMs = now;
        uiDirty = true;
      }
    } else if (view == VIEW_SEARCH) {
      // no list navigation on the search page
    } else if (now - lastNavMs >= 160) {
      if (up && cursor > 0) {
        --cursor;
        syncScroll();
        lastNavMs = now;
        uiDirty = true;
      }
      if (down && now - lastNavMs >= 160 &&
          cursor < (int)episodes.size() - 1) {
        ++cursor;
        syncScroll();
        lastNavMs = now;
        uiDirty = true;
      }
    }
  }

  // ---- volume (takes effect live during playback) ----
  static uint32_t lastVolMs = 0;
  if (volUp && now - lastVolMs >= 150 && player.volume < VOLUME_MAX) {
    ++player.volume;
    lastVolMs = now;
    audio.setVolume(player.volume);
    uiDirty = true;
  }
  if (volDn && now - lastVolMs >= 150 && player.volume > 0) {
    --player.volume;
    lastVolMs = now;
    audio.setVolume(player.volume);
    uiDirty = true;
  }

  // ---- 0 (keyboard) / B hold 1.5s (StickS3): open the WiFi setup hotspot on the list page ----
  static bool lastCfg = false;
#ifndef PODCAST_TARGET_STICKS3
  cfg = kb.isKeyPressed('0');  // keyboard-less targets set this in the A/B gesture layer above
#endif
  if (cfg && !lastCfg && view == VIEW_LIST) {
    bool connected = openPortal();
    // setup succeeded and there's no episode list yet -> fetch while at it
    if (connected && episodes.empty()) fetchWithProgress();
  }
  lastCfg = cfg;

#ifndef PODCAST_TARGET_STICKS3
  // ---- c: Top Podcasts charts, f: search (list page only; edge-triggered) ----
  static bool lastC = false, lastF = false;
  bool keyC = kb.isKeyPressed('c');
  bool keyF = kb.isKeyPressed('f');
  if (keyC && !lastC && view == VIEW_LIST) openCharts();
  static bool lastO = false;
  bool keyO = kb.isKeyPressed('o');
  if (keyO && !lastO && view == VIEW_LIST) toggleEpisodeOrder();
  lastO = keyO;
  if (keyF && !lastF && view == VIEW_LIST) {
    searchQuery.clear();
    searchOpenedMs = millis();
    view = VIEW_SEARCH;
    uiDirty = true;
  }
  lastC = keyC;
  lastF = keyF;

  // ---- Tab: channel switcher page toggle (the Esc key isn't reported by the M5Cardputer keyboard library, so Tab is used instead) ----
  static bool lastTab = false;
  bool tab = kb.isKeyPressed('\t');
  if (tab && !lastTab) {
    if (view == VIEW_CHANNEL || view == VIEW_SHOWS || view == VIEW_SEARCH) {
      view = VIEW_LIST;        // press Tab again to return to the list
    } else if (view == VIEW_LIST) {
      chanCursor = chanIdx;    // position the cursor on the current channel when opening
      view       = VIEW_CHANNEL;
    }
    uiDirty = true;
  }
  lastTab = tab;
#endif  // !PODCAST_TARGET_STICKS3

  // ---- Enter (edge-triggered; long press does not repeat) ----
  // channel page: Enter confirms the switch; list page: Enter selects the current episode = opens its player page
  // (starts playback if not playing); player page: Enter = pause / resume / replay
  static bool lastEnter = false;
  if (enter && !lastEnter) {
    if (view == VIEW_CHANNEL) {
      switchChannel(chanCursor);
    } else if (view == VIEW_SEARCH) {
      runSearch();
    } else if (view == VIEW_SHOWS) {
      openShow(showCursor);
    } else if (episodes.empty()) {
      fetchWithProgress();                    // list empty: retry
    } else if (view == VIEW_PLAYER) {
      if (audio.isRunning() && !paused) {
        // currently playing -> pause
        audio.pauseResume();
        paused = true;
      } else if (paused) {
        // paused -> resume; if paused too long and the CDN disconnects, loop turns it into an EOF hint
        audio.pauseResume();
        paused = false;
        audio.loop();                         // feed once immediately to probe whether the connection is alive
        if (!audio.isRunning()) statusMsg = "Link dropped, Enter: replay";
      } else {
        startPlayback(player.current >= 0 ? player.current : cursor);
      }                                      // finished/connect failed -> replay
      uiDirty = true;
    } else if (player.current == cursor) {
      // list page selecting the playing/paused episode -> just enter the player page, don't change playback state
      view = VIEW_PLAYER;
      uiDirty = true;
    } else {
      startPlayback(cursor);                  // play the newly selected episode
    }
  }
  lastEnter = enter;
}

// --------------------------- Main flow ---------------------------

void setup() {
#ifdef PODCAST_TARGET_STICKS3
  // CPU 240 -> 160MHz: ample headroom for AAC decoding, notably less heat and power
  // (the whole unit gets too hot during continuous playback). Before M5.begin, applies throughout
  setCpuFrequencyMhz(160);
#endif
  auto cfg = M5.config();
  // The onboard speaker/mic are fully driven by ESP32-audioI2S itself;
  // M5Unified only handles the display, board detection and internal I2C bus
  cfg.internal_spk = false;
  cfg.internal_mic = false;
#ifdef PODCAST_TARGET_STICKS3
  M5.begin(cfg);  // StickS3 is auto-detected by M5Unified at runtime
#else
  M5Cardputer.begin(cfg);
#endif

  Serial.begin(115200);
  auto& d = M5.Display;
#ifdef PODCAST_TARGET_STICKS3
  d.setRotation(1);  // native 135x240 portrait -> rotate to 240x135 landscape (same layout as Cardputer)
#endif
  Serial.printf("[app] display %dx%d resetReason=%d\n", (int)d.width(),
                (int)d.height(), (int)esp_reset_reason());

  // List layout computed from the actual screen height (CardputerADV canvas 240x135)
  listTop = 20;
  lineHeight = 19;
  listLines = (d.height() - listTop) / lineHeight;
  if (listLines < 1) listLines = 1;

  d.setTextDatum(m5gfx::textdatum_t::top_left);
  d.setFont(&fonts::efontCN_16);
  d.fillScreen(C_BG);
  d.setTextColor(C_TEXT, C_BG);

  // ---- Channel loading ----
  d.drawString("Loading channels...", 2, 1);
#ifdef PODCAST_TARGET_STICKS3
  // StickS3 version: single channel. Prefer a custom channel saved on the config page (NVS, change
  // without reflashing), else the firmware built-in channel. Editing RSS on the config page: see applyPortalChannel
  {
    ChannelEntry ce;
    Preferences p;
    p.begin("stickchan", true);
    String nvsRss   = p.getString("rss", "");
    String nvsName  = p.getString("name", "");
    p.end();
    if (nvsRss.length() > 0) {
      ce.name = nvsName.length() ? nvsName.c_str() : STICKS3_CHANNEL_NAME;
      ce.rss  = nvsRss.c_str();
      Serial.printf("[chan] custom channel from NVS: %s\n", ce.rss.c_str());
    } else {
      ce.name = STICKS3_CHANNEL_NAME;
      ce.rss  = STICKS3_CHANNEL_RSS;
      Serial.println("[chan] built-in single channel");
    }
    channels.push_back(ce);
  }
#else
  // SD /channels.txt > NVS cache > compiled-in
  {
    sdSPI.begin(PIN_SD_SCK, PIN_SD_MISO, PIN_SD_MOSI, PIN_SD_CS);
    sdReady = SD.begin(PIN_SD_CS, sdSPI, 25000000);
    Serial.printf("[sd] %s\n", sdReady ? "mounted" : "not found");
  }

  bool fromSD = false;
  if (sdReady) {
    File f = SD.open("/channels.txt");
    if (f) {
      std::string txt;
      txt.reserve(f.size());
      while (f.available()) txt.push_back((char)f.read());
      f.close();
      if (txt.size() >= 3 && (uint8_t)txt[0] == 0xEF &&
          (uint8_t)txt[1] == 0xBB && (uint8_t)txt[2] == 0xBF) {
        txt.erase(0, 3);  // strip UTF-8 BOM
      }
      size_t pos = 0;
      while (pos < txt.size() && channels.size() < 16) {
        size_t eol = txt.find('\n', pos);
        std::string line = txt.substr(
            pos, eol == std::string::npos ? std::string::npos : eol - pos);
        pos = (eol == std::string::npos) ? txt.size() : eol + 1;
        if (!line.empty() && line.back() == '\r') line.pop_back();
        size_t b = line.find_first_not_of(" \t");
        if (b == std::string::npos) continue;
        size_t e = line.find_last_not_of(" \t");
        line = line.substr(b, e - b + 1);
        if (line[0] == '#') continue;  // comment line
        // split by | and trim leading/trailing whitespace
        std::vector<std::string> parts;
        size_t p2 = 0;
        while (true) {
          size_t bar = line.find('|', p2);
          std::string seg = line.substr(
              p2, bar == std::string::npos ? std::string::npos : bar - p2);
          size_t sb = seg.find_first_not_of(" \t");
          parts.push_back(sb == std::string::npos
                              ? ""
                              : seg.substr(sb,
                                           seg.find_last_not_of(" \t") - sb + 1));
          if (bar == std::string::npos) break;
          p2 = bar + 1;
        }
        if (parts.size() < 2 || parts[0].empty() ||
            parts[1].compare(0, 4, "http") != 0) {
          Serial.printf("[chan] skip bad line: %s\n", line.c_str());
          continue;
        }
        ChannelEntry ce;
        ce.name     = parts[0];
        ce.rss      = parts[1];
        channels.push_back(ce);
      }
      fromSD = !channels.empty();
      Serial.printf("[chan] SD: %d channels\n", (int)channels.size());
    } else {
      Serial.println("[chan] SD: no /channels.txt");
    }
  }

  if (fromSD) {
    // SD config parsed successfully -> cache into NVS, fallback when the card is removed/bad
    // (blob2 = v2 layout: [u8 name len][name][u8 rss len][rss], no cover field)
    std::string blob;
    for (auto& c : channels) {
      blob.push_back((char)c.name.size());
      blob.append(c.name);
      blob.push_back((char)c.rss.size());
      blob.append(c.rss);
    }
    Preferences p;
    p.begin("chanlist", false);
    p.putBytes("blob2", blob.data(), blob.size());
    p.end();
  } else {
    // SD not configured -> read the last cached channel list
    Preferences p;
    p.begin("chanlist", true);
    size_t n = p.getBytesLength("blob2");
    if (n > 0) {
      std::vector<char> buf(n);
      p.getBytes("blob2", buf.data(), n);
      p.end();
      size_t cpos = 0;
      while (cpos + 2 <= buf.size() && channels.size() < 16) {
        size_t nl = (uint8_t)buf[cpos++];
        if (cpos + nl > buf.size()) break;
        ChannelEntry ce;
        ce.name.assign(buf.data() + cpos, nl);
        cpos += nl;
        if (cpos >= buf.size()) break;
        size_t rl = (uint8_t)buf[cpos++];
        if (cpos + rl > buf.size()) break;
        ce.rss.assign(buf.data() + cpos, rl);
        cpos += rl;
        channels.push_back(ce);
      }
      if (!channels.empty()) {
        Serial.printf("[chan] NVS cache: %d channels\n", (int)channels.size());
      }
    } else {
      p.end();
    }
  }
#endif  // !PODCAST_TARGET_STICKS3

  if (channels.empty()) {
    // final fallback: compiled-in channel table (works even if channels.txt is missing)
    for (int i = 0; i < CHANNEL_COUNT; ++i) {
      ChannelEntry ce;
      ce.name = CHANNELS[i].name;
      ce.rss  = CHANNELS[i].rss;
      channels.push_back(ce);
    }
    Serial.println("[chan] using embedded channels");
  }

  // last selected channel (NVS, out-of-range falls back to index 0)
  {
    Preferences p;
    p.begin("chan", true);
    chanIdx = p.getUChar("idx", 0);
    p.end();
    if (chanIdx < 0 || chanIdx >= (int)channels.size()) chanIdx = 0;
  }
  Serial.printf("[app] channel %d: %s\n", chanIdx,
                channels[chanIdx].name.c_str());

  // Crash forensics: show the reason for the previous reset on the boot screen (to diagnose crashes without a PC)
  // esp_reset_reason: 1=normal power-on 2=software restart 3=panic 4=interrupt watchdog 5=task watchdog
  //                   6=hardware watchdog 7=deep-sleep wake 8=brownout (voltage drop)
  {
    esp_reset_reason_t r = esp_reset_reason();
    const char* why;
    switch (r) {
      case ESP_RST_POWERON:   why = "power-on";     break;
      case ESP_RST_SW:        why = "soft reset";   break;
      case ESP_RST_PANIC:     why = "panic!";       break;
      case ESP_RST_INT_WDT:   why = "int WDT!";     break;
      case ESP_RST_TASK_WDT:  why = "task WDT!";    break;
      case ESP_RST_WDT:       why = "hw WDT!";      break;
      case ESP_RST_DEEPSLEEP: why = "deep sleep";   break;
      case ESP_RST_BROWNOUT:  why = "brownout!";    break;
      default:                why = "unknown";     break;
    }
    Serial.printf("[app] resetReason=%d heapNow=%u heapMin=%u\n", (int)r,
                  (unsigned)ESP.getFreeHeap(), (unsigned)ESP.getMinFreeHeap());
    if (r != ESP_RST_POWERON && r != ESP_RST_DEEPSLEEP) {
      d.fillRect(0, 18, d.width(), 16, C_BG);
      d.setTextColor(C_TEXT, C_BG);
      d.drawString(String("Last abort: ") + why, 2, 18);
      delay(4000);  // stay 4 seconds on abnormal reset so the reason is clearly visible
    }
  }

  d.fillScreen(C_BG);
  d.setTextColor(C_TEXT, C_BG);
  d.drawString("Connecting Wi-Fi...", 2, 1);

  // 1) WiFi: WiFiManager fully managed -- tries NVS stored credentials first, auto-starts the hotspot on failure
  //    "PodcastPlayer" + captive portal (phone joins and the config page auto-pops)
  WiFiManager wm;
  makePortalPassword();
  wm.setConnectTimeout(10);          // wait for a connect attempt with stored credentials
  wm.setConfigPortalTimeout(180);    // auto-close the hotspot after 3 min of inactivity
  wm.setAPCallback([](WiFiManager*) { drawPortalScreen(); });
#ifdef PODCAST_TARGET_STICKS3
  // Config page includes channel settings (users can fill in their own RSS on first boot)
  WiFiManagerParameter prmName("chan", "Channel name", channels[0].name.c_str(), 48);
  WiFiManagerParameter prmRss("rss", "Podcast RSS URL",
                              channels[0].rss.c_str(), 256);
  wm.addParameter(&prmName);
  wm.addParameter(&prmRss);
#endif
  wifiOk = wm.autoConnect(AP_NAME, portalPass);
  if (wifiOk) {
    WiFi.setSleep(false);           // online streaming needs stable throughput
    WiFi.setAutoReconnect(true);    // auto-reconnect at the low level after a router blip
  }
#ifdef PODCAST_TARGET_STICKS3
  // If RSS was changed during first configuration: channels[0] is already updated, the first fetch below uses the new source
  applyPortalChannel(prmName.getValue(), prmRss.getValue());
  refetchNeeded = false;  // the tail of setup fetches anyway, no extra trigger needed
#endif
  Serial.printf("[app] wifi %s\n", wifiOk ? "connected" : "FAILED");

  // 2) RSS episode list (ES8311 is initialized lazily on first playback, needs the I2S clock running first)
  d.fillScreen(C_BG);
  if (wifiOk) {
    fetchWithProgress();
  } else {
    d.setTextColor(C_WARN, C_BG);
    d.drawString("Wi-Fi not connected", 2, 1);
    d.drawString("Press 0 for WiFi setup", 2, 21);
    d.setTextColor(C_TEXT, C_BG);
  }

  uiDirty = true;
}

void loop() {
#ifdef PODCAST_TARGET_STICKS3
  M5.update();  // refresh BtnA/BtnB state (for wasClicked/isPressed)
#else
  M5Cardputer.update();
#endif
  handleKeys();
#ifdef PODCAST_TARGET_STICKS3
  // RSS changed on the config page: refetch the new channel's episodes after returning to the list
  if (refetchNeeded && !audio.isRunning()) {
    refetchNeeded = false;
    view = VIEW_LIST;
    fetchWithProgress();
  }
#endif
  ampTick();  // delayed amp enable + volume fade-in (brownout avoidance)

  // Feed the decoder (returns immediately when paused). EOF detection:
  // was running last pass, gone this pass, and not a user pause -> finished
  audio.loop();
  static bool wasRunning = false;
  bool running = audio.isRunning();
  if (wasRunning && !running && !paused && statusMsg.empty()) {
    statusMsg = "Finished";
    uiDirty = true;
  }
  wasRunning = running;

  // Player page progress bar partial refresh once per second (a static page isn't fully redrawn)
  static uint32_t lastProgressMs = 0;
  if (view == VIEW_PLAYER && audio.isRunning() && !paused &&
      millis() - lastProgressMs >= 1000) {
    lastProgressMs = millis();
    drawPlayerPage(false);
  }

  // While playing, check WiFi every pass: a drop cleanly stops the stream immediately.
  // Continuing to decode on a dead socket is the root cause of crackle for a few minutes then crash-reboot
  if (audio.isRunning() && WiFi.status() != WL_CONNECTED) {
    int sec = audio.getAudioCurrentTime();
    audio.stopSong();
    paused = false;
    wifiDropPause = true;
    char buf[64];
    snprintf(buf, sizeof(buf), "WiFi lost %02d:%02d, Enter: replay",
             sec / 60, sec % 60);
    statusMsg = buf;
    Serial.printf("[net] dropped while playing at %ds\n", sec);
    uiDirty = true;
  }

  // WiFi auto-reconnect + heap monitoring (low frequency)
  static uint32_t lastWifiCheck = 0;
  if (millis() - lastWifiCheck > 3000) {
    lastWifiCheck = millis();
    bool ok = (WiFi.status() == WL_CONNECTED);
    if (!ok) WiFi.reconnect();
    if (ok != wifiOk) {
      wifiOk = ok;
      if (ok && wifiDropPause && !audio.isRunning()) {
        wifiDropPause = false;
        statusMsg = "Wi-Fi restored, Enter: replay";
      }
      uiDirty = true;
    }
    Serial.printf("[net] wifi=%d heap=%u minHeap=%u\n", ok,
                  (unsigned)ESP.getFreeHeap(), (unsigned)ESP.getMinFreeHeap());
  }

  if (uiDirty) {
    drawUI();
    uiDirty = false;
  }
}
