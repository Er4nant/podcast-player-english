// Parse a single <item>...</item> with TinyXML2, extracting the title and the enclosure direct link
static void parseEpisodeXml(const std::string& xml, std::vector<Episode>& out) {
  tinyxml2::XMLDocument doc;
  if (doc.Parse(xml.data(), xml.size()) != tinyxml2::XML_SUCCESS) return;
  const tinyxml2::XMLElement* item = doc.RootElement();
  if (item == nullptr) return;
  const tinyxml2::XMLElement* titleEl = item->FirstChildElement("title");
  const tinyxml2::XMLElement* encEl   = item->FirstChildElement("enclosure");
  if (titleEl == nullptr || encEl == nullptr) return;
  const char* t = titleEl->GetText();
  const char* u = encEl->Attribute("url");
  if (t == nullptr || u == nullptr) return;
  Episode ep;
  ep.title = cleanText(t);
  ep.url   = cleanText(u);
  if (!ep.title.empty() && !ep.url.empty()) out.push_back(ep);
}

// Streaming RSS fetch: the sliding window only buffers a single <item>; everything else is read and discarded.
// Returns whether at least one episode was parsed. isHttps=false uses a plaintext WiFiClient,
// bypassing mbedtls (the TLS stack uses a lot of memory, the biggest heap peak during fetch);
// in plaintext mode a redirect to https fails, handled by a fallback at the call site.
extern const uint8_t _binary_x509_crt_bundle_start[];  // IDF CA bundle (libmbedtls)
static bool fetchEpisodesFrom(const char* url, bool isHttps,
                              std::vector<Episode>& eps) {
  WiFiClientSecure secureClient;
  WiFiClient       plainClient;
  HTTPClient http;
  // Verify server certificates against the IDF Mozilla CA bundle (embedded in libmbedtls).
  // Without this, anyone on the path could substitute a fake feed.
  if (isHttps) secureClient.setCACertBundle(_binary_x509_crt_bundle_start);
  bool began = isHttps ? http.begin(secureClient, url)
                       : http.begin(plainClient, url);
  if (!began) return false;
  http.setFollowRedirects(HTTPC_STRICT_FOLLOW_REDIRECTS);
  http.setUserAgent("CardputerPodcast/1.0");
  http.setConnectTimeout(10000);
  int code = http.GET();
  if (code != HTTP_CODE_OK) {
    Serial.printf("[rss] HTTP GET code=%d\n", code);
    http.end();
    return false;
  }
  WiFiClient* stream = http.getStreamPtr();
  if (stream == nullptr) {
    http.end();
    return false;
  }
  stream->setTimeout(8000);

  std::string pending;   // small buffer when not inside an item (to match "<item" across chunks)
  std::string item;      // accumulation buffer for the current item
  bool inItem = false;
  size_t total = 0;
  uint8_t buf[1024];

  while (eps.size() < MAX_EPISODES && total < MAX_FEED_BYTES) {
    int n = (int)stream->readBytes(buf, sizeof(buf));
    if (n <= 0) break;  // stream ended
    total += (size_t)n;

    if (!inItem) {
      pending.append((const char*)buf, (size_t)n);
      size_t pos = pending.find("<item");
      if (pos != std::string::npos) {
        inItem = true;
        item = pending.substr(pos);
        pending.clear();
      } else if (pending.size() > 8) {
        // keep only the trailing 8 bytes, enough to match a cross-chunk "<item"
        pending.erase(0, pending.size() - 8);
      }
    } else {
      item.append((const char*)buf, (size_t)n);
      size_t pos = item.find("</item>");
      if (pos != std::string::npos) {
        // a complete item: hand it to TinyXML2
        parseEpisodeXml(item.substr(0, pos + 7), eps);
        // for the remaining content only backfill the trailing 8 bytes (enough to match a cross-chunk "<item");
        // don't copy the whole item tail (a wasted copy of up to several KB)
        size_t remStart = pos + 7;
        if (item.size() - remStart > 8) remStart = item.size() - 8;
        pending.assign(item, remStart, std::string::npos);
        item.clear();
        inItem = false;
      } else if (item.size() > MAX_ITEM_BYTES) {
        // abnormally long item: cannot clear the whole thing -- the buffer may already contain the start
        // of the next <item; discarding it directly would misalign parsing of later items (corrupt URL join).
        // Instead resync within the buffer to the next <item:
        size_t nxt = item.find("<item", 1);
        if (nxt != std::string::npos) {
          item.erase(0, nxt);  // continue collecting from the start of the next item
        } else {
          // no next one in the buffer: keep only the trailing 8 bytes for cross-chunk "<item" matching
          pending.assign(item, item.size() - 8, std::string::npos);
          item.clear();
          inItem = false;
        }
        Serial.println("[rss] item too large, resynced");
      }
    }
  }
  http.end();
  Serial.printf("[rss] %u episodes, %u bytes\n",
                (unsigned)eps.size(), (unsigned)total);
  return !eps.empty();
}

// Same strategy as playback: try a plaintext http direct link first (saves tens of KB of mbedtls heap peak),
// fall back to the original https address on failure.
static bool fetchEpisodesUrl(const std::string& feedUrl, std::vector<Episode>& eps) {
  String rss = String(feedUrl.c_str());
  if (rss.startsWith("http://")) {
    return fetchEpisodesFrom(rss.c_str(), false, eps);
  }
  String httpUrl = rss;
  httpUrl.replace("https://", "http://");
  Serial.printf("[rss] try http: %s\n", httpUrl.c_str());
  if (fetchEpisodesFrom(httpUrl.c_str(), false, eps)) return true;
  Serial.println("[rss] http failed, fallback to https");
  return fetchEpisodesFrom(rss.c_str(), true, eps);
}

static bool fetchEpisodes(std::vector<Episode>& eps) {
  return fetchEpisodesUrl(activeFeedUrl.empty() ? channels[chanIdx].rss : activeFeedUrl, eps);
}

// Fetch entry with on-screen hints (shared by first boot and the Enter retry when the list is empty)
static void fetchWithProgress() {
  statusMsg = "Fetch: " + (activeFeedName.empty() ? channels[chanIdx].name : activeFeedName);
  uiDirty = true;
  drawUI();
  uiDirty = false;

  episodes.clear();
  fetchEpisodes(episodes);
  cursor = 0;
  scrollTop = 0;
  statusMsg = episodes.empty() ? "Fetch failed, Enter: retry" : "";
  uiDirty = true;
}

// Switch channel: stop playback, clear the list, remember in NVS, refetch RSS (picking the same channel just returns to the list)
static void switchChannel(int idx) {
  if (idx < 0 || idx >= (int)channels.size()) return;
  activeFeedUrl.clear();   // leaving a discovered show
  activeFeedName.clear();
  if (idx != chanIdx) {
    if (audio.isRunning()) {
      audio.stopSong();
      while (audio.isRunning()) delay(10);  // wait until the decode thread fully stops before touching channel data
    }
    paused         = false;
    player.current = -1;
    chanIdx        = idx;
    Preferences p;
    p.begin("chan", false);
    p.putUChar("idx", (uint8_t)chanIdx);
    p.end();
    // cover is a text badge, switching channels is zero-cost
    statusMsg = "Switched: " + channels[chanIdx].name;
  }
  view    = VIEW_LIST;
  uiDirty = true;
  if (wifiOk) {
    fetchWithProgress();
  } else {
    episodes.clear();
    cursor    = 0;
    scrollTop = 0;
    statusMsg = "No Wi-Fi, press 0 to set up";
  }
}

