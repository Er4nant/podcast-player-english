// Each channel picks a color scheme by name hash: gradient background + white corners + large channel name
static inline uint16_t RGB888(uint8_t r, uint8_t g, uint8_t b) {
  return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3);
}

struct CoverScheme {
  uint8_t  r1, g1, b1;  // gradient top
  uint8_t  r2, g2, b2;  // gradient bottom
  uint16_t text;        // text/corner color
};

static const CoverScheme kCoverSchemes[] = {
    { 96,  52, 176,   38,  14,  82, 0xFFFF},  // purple (Ni Da original color family)
    {  0, 128, 138,    0,  48,  72, 0xFFFF},  // cyan
    {178,  44,  64,   88,   8,  30, 0xFFFF},  // crimson
    {206, 116,  24,  122,  48,   8, 0xFFFF},  // orange
    { 28, 126,  96,    8,  58,  46, 0xFFFF},  // pine green
    { 52,  72, 190,   14,  22,  92, 0xFFFF},  // indigo
};
static const int kSchemeCount =
    sizeof(kCoverSchemes) / sizeof(kCoverSchemes[0]);

// FNV-1a hash: same-named channels always get the same colors
static uint32_t nameHash(const std::string& s) {
  uint32_t h = 2166136261u;
  for (unsigned char c : s) {
    h ^= c;
    h *= 16777619u;
  }
  return h ^ (h >> 16);
}

// Small color block on the channel list page (uses the gradient top color)
static uint16_t coverTopColor(const std::string& name) {
  const CoverScheme& sc = kCoverSchemes[nameHash(name) % kSchemeCount];
  return RGB888(sc.r1, sc.g1, sc.b1);
}

// Text cover: vertical gradient background + inner corners + centered large channel name + bottom accent line
static void drawCoverArt(int x, int y, int w, int h,
                         const std::string& name) {
  auto& d = M5.Display;
  const CoverScheme& sc = kCoverSchemes[nameHash(name) % kSchemeCount];

  // gradient background (per-row interpolation)
  for (int i = 0; i < h; ++i) {
    int t = (h > 1) ? i * 255 / (h - 1) : 0;
    uint8_t r = sc.r1 + (sc.r2 - sc.r1) * t / 255;
    uint8_t g = sc.g1 + (sc.g2 - sc.g1) * t / 255;
    uint8_t b = sc.b1 + (sc.b2 - sc.b1) * t / 255;
    d.drawFastHLine(x, y + i, w, RGB888(r, g, b));
  }

  // Four white L-shaped corners (badge feel)
  const int arm = 7, off = 5;
  uint16_t ln = sc.text;
  d.drawFastHLine(x + off, y + off, arm, ln);
  d.drawFastVLine(x + off, y + off, arm, ln);
  d.drawFastHLine(x + w - off - arm, y + off, arm, ln);
  d.drawFastVLine(x + w - off - 1, y + off, arm, ln);
  d.drawFastHLine(x + off, y + h - off - 1, arm, ln);
  d.drawFastVLine(x + off, y + h - off - arm, arm, ln);
  d.drawFastHLine(x + w - off - arm, y + h - off - 1, arm, ln);
  d.drawFastVLine(x + w - off - 1, y + h - off - arm, arm, ln);

  // Color is already picked by name hash; now lay out the text: first try 2x size (32px/char),
  // if it doesn't fit (more than 3 lines or over the line limit) fall back to 1x (16px/char)
  auto countChars = [](const std::string& s) {
    int n = 0;
    for (unsigned char c : s)
      if ((c & 0xC0) != 0x80) ++n;  // UTF-8 continuation bytes don't count
    return n;
  };
  int nch = countChars(name);
  int size = 1, cpl = (w - 20) / 16, maxLines = (h - 16) / 16;
  int lines = (nch + cpl - 1) / cpl;
  if (lines <= 3) {  // may fit large text
    int cpl2 = (w - 20) / 32;
    int mL2  = (h - 16) / 32;
    int ln2  = (nch + cpl2 - 1) / cpl2;
    if (ln2 >= 1 && ln2 <= mL2 && ln2 <= 3) {
      size = 2;
      cpl = cpl2;
      lines = ln2;
      maxLines = mL2;
    }
  }
  if (lines > maxLines) lines = maxLines;  // truncate overlong names
  if (lines < 1) lines = 1;

  // Centered layout drawing (breaks lines at UTF-8 codepoint boundaries)
  d.setTextDatum(m5gfx::textdatum_t::top_center);
  d.setTextColor(sc.text);  // transparent background, gradient shows through
  d.setTextSize(size);
  int lh     = 16 * size;
  int yStart = y + (h - lines * lh) / 2;
  std::string rem = name;
  for (int i = 0; i < lines && !rem.empty(); ++i) {
    int cnt = 0, cut = (int)rem.size();
    for (size_t p = 0; p < rem.size(); ++p) {
      if ((rem[p] & 0xC0) != 0x80 && ++cnt > cpl) {
        cut = (int)p;
        break;
      }
    }
    std::string seg = rem.substr(0, cut);
    d.drawString(seg.c_str(), x + w / 2, yStart + i * lh);
    rem.erase(0, cut);
  }

  // Small accent line below the text block (centered)
  int yEnd = yStart + lines * lh;
  if (yEnd + 8 <= y + h - off) {
    d.fillRect(x + w / 2 - 12, yEnd + 4, 24, 2, sc.text);
  }

  // Restore default text state (the rest of the page relies on top_left + size 1)
  d.setTextDatum(m5gfx::textdatum_t::top_left);
  d.setTextSize(1);
}
