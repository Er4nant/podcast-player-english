# -*- coding: utf-8 -*-
"""PlatformIO pre-build script: reads channels.txt and generates src/channels.h (embedded fallback channels).

Channel maintenance (no need to edit C++ code):
  1. Edit channels.txt in the repo root, one channel per line: Channel Name|RSS URL
  2. In production, put the same format in the SD card root (no reflashing needed, higher priority)
  3. Recompile to take effect

Cover art is a text badge generated at runtime from the channel name (gradient + large text), with no image assets.
A generation failure (bad txt format) raises an exception and aborts the build, to avoid flashing bad data.
"""
import os

# Locate the project root: __file__ may not exist when SCons exec runs the pre script,
# prefer the env and $PROJECT_DIR injected by PlatformIO; fall back to __file__ when run manually
try:
    Import("env")  # noqa: F821  SCons built-in
    ROOT_DIR = env.subst("$PROJECT_DIR")
except NameError:
    try:
        ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    except NameError:
        raise SystemExit("gen_channels: cannot locate project root directory")

TXT_PATH = os.path.join(ROOT_DIR, "channels.txt")
OUT_PATH = os.path.join(ROOT_DIR, "src", "channels.h")


def parse_channels():
    """Parse channels.txt -> [(name, rss), ...]"""
    if not os.path.exists(TXT_PATH):
        raise SystemExit("gen_channels: missing %s" % TXT_PATH)
    with open(TXT_PATH, encoding="utf-8-sig") as f:
        raw = f.read()
    chans = []
    for lineno, line in enumerate(raw.splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 2 or not parts[0] or not parts[1].startswith("http"):
            raise SystemExit(
                "gen_channels: channels.txt line %d has a bad format (expected Channel Name|RSS URL): %r"
                % (lineno, line))
        chans.append((parts[0], parts[1]))
    if not chans:
        raise SystemExit("gen_channels: no channels found in channels.txt")
    return chans


def main():
    chans = parse_channels()
    lines = []
    lines.append("// Auto-generated by tools/gen_channels.py (data source: channels.txt)")
    lines.append("// Hand edits are discarded on the next build; to add channels, edit channels.txt")
    lines.append("#pragma once")
    lines.append("")
    lines.append("// Channel definitions: name / RSS URL (cover is a text badge generated at runtime from the name)")
    lines.append("struct ChannelDef {")
    lines.append("  const char* name;")
    lines.append("  const char* rss;")
    lines.append("};")
    lines.append("")
    lines.append("static const ChannelDef CHANNELS[] = {")
    for name, rss in chans:
        lines.append('    {"%s", "%s"},' % (name, rss))
    lines.append("};")
    lines.append("")
    lines.append("static const int CHANNEL_COUNT =")
    lines.append("    sizeof(CHANNELS) / sizeof(CHANNELS[0]);")
    lines.append("")
    with open(OUT_PATH, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("gen_channels: %d channels -> %s" % (len(chans), OUT_PATH))


if __name__ == "__main__":
    main()
